/** A fence opening line's language ("" when it has none), or null when the line opens no fence. */
function fenceLang(line) {
  if (line.charCodeAt(0) !== 96 || line.charCodeAt(1) !== 96 || line.charCodeAt(2) !== 96) return null;
  let i = 3;
  while (i < line.length) {
    const c = line.charCodeAt(i);
    if ((c >= 65 && c <= 90) || (c >= 97 && c <= 122) || (c >= 48 && c <= 57) || c === 95 || c === 43 || c === 45) i++;
    else break;
  }
  const lang = line.slice(3, i);
  while (i < line.length) {
    const c = line.charCodeAt(i);
    if (c !== 32 && c !== 9) return null;
    i++;
  }
  return lang;
}

/** Whether `line` closes a fence: three backticks, then spaces or tabs only. */
function isFenceClose(line) {
  if (line.charCodeAt(0) !== 96 || line.charCodeAt(1) !== 96 || line.charCodeAt(2) !== 96) return false;
  for (let i = 3; i < line.length; i++) {
    const c = line.charCodeAt(i);
    if (c !== 32 && c !== 9) return false;
  }
  return true;
}

/** A heading line's { depth, text }, or null (a heading's text is never empty). */
function headingOf(line) {
  let d = 0;
  while (d < line.length && line.charCodeAt(d) === 35) d++;
  if (d === 0 || d > 6) return null;
  const c = line.charCodeAt(d);
  if (c !== 32 && c !== 9) return null;
  let j = d;
  while (j < line.length && (line.charCodeAt(j) === 32 || line.charCodeAt(j) === 9)) j++;
  let e = line.length;
  while (e > j && (line.charCodeAt(e - 1) === 32 || line.charCodeAt(e - 1) === 9)) e--;
  if (e === j) return null;
  return { depth: d, text: line.slice(j, e) };
}

/** Whether `line` is a thematic break: "---" or "***", then spaces or tabs only. */
function isHR(line) {
  const c = line.charCodeAt(0);
  if ((c !== 45 && c !== 42) || line.charCodeAt(1) !== c || line.charCodeAt(2) !== c) return false;
  for (let i = 3; i < line.length; i++) {
    const cc = line.charCodeAt(i);
    if (cc !== 32 && cc !== 9) return false;
  }
  return true;
}

/**
 * A list item line's text after its marker, or null. `ordered` selects the marker kind; a bullet
 * list takes "-" or "*", an ordered list 1-9 digits and ". ". When `first` is an object, its
 * `start` is set from an ordered list's first number.
 */
function listItemText(line, ordered) {
  if (ordered) {
    let d = 0;
    while (d < line.length) {
      const c = line.charCodeAt(d);
      if (c >= 48 && c <= 57) d++;
      else break;
    }
    if (d === 0 || d > 9 || line.charCodeAt(d) !== 46 || line.charCodeAt(d + 1) !== 32) return null;
    return line.slice(d + 2);
  }
  const c = line.charCodeAt(0);
  if ((c === 45 || c === 42) && line.charCodeAt(1) === 32) return line.slice(2);
  return null;
}

/** Whether `line` continues a list item: two or more spaces, then a non-space. */
function isContinued(line) {
  let i = 0;
  while (i < line.length && line.charCodeAt(i) === 32) i++;
  return i >= 2 && i < line.length && !isWSCode(line.charCodeAt(i));
}

/** Whether `line` ends a paragraph: blank, a fence opening, a heading or a thematic break. */
function endsParagraph(line) {
  return isBlankST(line) || fenceLang(line) !== null || headingOf(line) !== null || isHR(line);
}

/** The characters a backslash escapes. */
const ESCAPABLE = new Set(['\\', '`', '*', '_', '[', ']', '(', ')', '#', '+', '-', '.', '!', '>']);

/** The first index in [from, end) where `s` holds `what` outside a backslash escape, or -1. */
function findUnescaped(s, what, from, end) {
  const wlen = what.length;
  for (let j = from; j <= end - wlen; j++) {
    if (s.charCodeAt(j) === 92 && j + 1 < end && ESCAPABLE.has(s[j + 1])) {
      j++;
      continue;
    }
    if (s.startsWith(what, j)) return j;
  }
  return -1;
}

/** The first single * in [from, end) (one whose run is not **), outside an escape, or -1. */
function findSingleStar(s, from, end) {
  for (let j = from; j < end; j++) {
    const c = s[j];
    if (c === '\\' && j + 1 < end && ESCAPABLE.has(s[j + 1])) {
      j++;
      continue;
    }
    if (c !== '*') continue;
    if (j + 1 < end && s[j + 1] === '*') {
      j++;
      continue;
    }
    return j;
  }
  return -1;
}

const WS_RE = /\s/;
const STOP_RE = /[\\`*[]/g;

/**
 * The range [i0, i1) of `s` rendered inline; `linkFn(target)` is a link's href. A regex jumps
 * from construct to construct (the characters \ ` * [), the plain text between them is escaped
 * a run at a time, and constructs recurse on sub-ranges — nothing is sliced but the runs and
 * the link targets themselves.
 */
function inlineRange(s, i0, i1, linkFn) {
  let out = '';
  let i = i0;
  while (i < i1) {
    STOP_RE.lastIndex = i;
    const m = STOP_RE.exec(s);
    const stop = m === null || m.index >= i1 ? i1 : m.index;
    if (stop > i) {
      out += escapeHtml(s.slice(i, stop));
      i = stop;
      if (i >= i1) break;
    }
    const cc = s.charCodeAt(i);
    if (cc === 92) {
      // "\"
      if (i + 1 < i1 && ESCAPABLE.has(s[i + 1])) {
        out += escapeHtml(s[i + 1]);
        i += 2;
      } else {
        out += '\\';
        i++;
      }
      continue;
    }
    if (cc === 96) {
      // "`"
      const j = s.indexOf('`', i + 1);
      if (j !== -1 && j < i1 && j > i + 1) {
        out += `<code>${escapeHtml(s.slice(i + 1, j))}</code>`;
        i = j + 1;
      } else {
        out += '`';
        i++;
      }
      continue;
    }
    if (cc === 42) {
      // "*"
      if (i + 1 < i1 && s[i + 1] === '*') {
        const j = findUnescaped(s, '**', i + 2, i1);
        if (j > i + 2) {
          out += `<strong>${inlineRange(s, i + 2, j, linkFn)}</strong>`;
          i = j + 2;
        } else {
          out += '**';
          i += 2;
        }
        continue;
      }
      const j = findSingleStar(s, i + 1, i1);
      if (j > i + 1) {
        out += `<em>${inlineRange(s, i + 1, j, linkFn)}</em>`;
        i = j + 1;
      } else {
        out += '*';
        i++;
      }
      continue;
    }
    // "[" (the only other stop character)
    const k = findUnescaped(s, ']', i + 1, i1);
    let linked = false;
    if (k !== -1 && k + 1 < i1 && s[k + 1] === '(') {
      const m2 = s.indexOf(')', k + 2);
      if (m2 !== -1 && m2 < i1) {
        const target = s.slice(k + 2, m2);
        if (target !== '' && !WS_RE.test(target)) {
          out += `<a href="${escapeHtml(linkFn(target))}">${inlineRange(s, i + 1, k, linkFn)}</a>`;
          i = m2 + 1;
          linked = true;
        }
      }
    }
    if (!linked) {
      out += '[';
      i++;
    }
  }
  return out;
}

/**
 * `src` rendered: its HTML (a "\n" after every block), its table of contents (every level 2 and 3
 * heading: level, id and its inline HTML) and its excerpt (the first paragraph's inline HTML, or
 * ""). `slugify` is the build's memoised slug function; heading ids are made unique per page.
 */
function renderMarkdown(src, linkFn, slugify) {
  const lines = src.split('\n');
  const n = lines.length;
  const ids = new Set();
  const toc = [];
  let excerpt = null;
  let html = '';
  let i = 0;
  while (i < n) {
    const line = lines[i];
    if (isBlankST(line)) {
      i++;
      continue;
    }
    const lang = fenceLang(line);
    if (lang !== null) {
      i++;
      let body = '';
      while (i < n && !isFenceClose(lines[i])) {
        body += `${escapeHtml(lines[i])}\n`;
        i++;
      }
      i++;
      html += `<pre><code${lang === '' ? '' : ` class="language-${escapeHtml(lang)}"`}>${body}</code></pre>\n`;
      continue;
    }
    const heading = headingOf(line);
    if (heading !== null) {
      const id = uniqueSlug(slugify(heading.text), ids);
      const h = inlineRange(heading.text, 0, heading.text.length, linkFn);
      html += `<h${heading.depth} id="${id}">${h}</h${heading.depth}>\n`;
      if (heading.depth === 2 || heading.depth === 3) toc.push({ level: heading.depth, id, html: h });
      i++;
      continue;
    }
    if (isHR(line)) {
      html += '<hr>\n';
      i++;
      continue;
    }
    if (line.charCodeAt(0) === 62) {
      const parts = [];
      while (i < n && lines[i].charCodeAt(0) === 62) {
        const raw = lines[i];
        const stripped = trimST(raw.startsWith('> ') ? raw.slice(2) : raw.slice(1));
        if (stripped !== '') parts.push(stripped);
        i++;
      }
      if (parts.length === 0) html += '<blockquote>\n</blockquote>\n';
      else {
        const joined = parts.join('\n');
        html += `<blockquote>\n<p>${inlineRange(joined, 0, joined.length, linkFn)}</p>\n</blockquote>\n`;
      }
      continue;
    }
    const firstBullet = listItemText(line, false);
    const firstOrdered = firstBullet === null ? listItemText(line, true) : null;
    if (firstBullet !== null || firstOrdered !== null) {
      const ordered = firstOrdered !== null;
      let start = 1;
      if (ordered) {
        let d = 0;
        while (line.charCodeAt(d) >= 48 && line.charCodeAt(d) <= 57) d++;
        start = Number(line.slice(0, d));
      }
      const items = [];
      let cur = [trimST(ordered ? firstOrdered : firstBullet)];
      items.push(cur);
      i++;
      while (i < n) {
        const t = listItemText(lines[i], ordered);
        if (t !== null) {
          cur = [trimST(t)];
          items.push(cur);
          i++;
        } else if (isContinued(lines[i])) {
          cur.push(trimST(lines[i]));
          i++;
        } else break;
      }
      const tag = ordered ? 'ol' : 'ul';
      const open = ordered && start !== 1 ? `<ol start="${start}">` : `<${tag}>`;
      let block = `${open}\n`;
      for (const parts of items) {
        const item = parts.join('\n');
        block += `<li>${inlineRange(item, 0, item.length, linkFn)}</li>\n`;
      }
      html += `${block}</${tag}>\n`;
      continue;
    }
    let text = trimST(line);
    i++;
    while (i < n && !endsParagraph(lines[i])) {
      text += `\n${trimST(lines[i])}`;
      i++;
    }
    const h = inlineRange(text, 0, text.length, linkFn);
    if (excerpt === null) excerpt = h;
    html += `<p>${h}</p>\n`;
  }
  return { html, toc, excerpt: excerpt ?? '' };
}

