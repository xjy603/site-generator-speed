// A faster drop-in replacement for makefun-site 1.0.0, written from its README spec and observed
// behaviour. run(input) returns the same output tree (path -> text) that makefun-site's build
// returns for one case's { site, templates, files }, byte for byte.
//
// Where this differs from the reference's shape: the Markdown inline renderer works on index
// ranges of the block text instead of slicing a fresh string at every construct, plain text is
// escaped a run at a time instead of a character at a time, block lines are classified by their
// first characters instead of a stack of regexes, and slugify results are memoised for the span
// of one build (titles, tag names and headings repeat a lot inside one site).

// ---------------------------------------------------------------- text rules

/** `s` with & < > " ' escaped; returns `s` itself when there is nothing to escape. */
function escapeHtml(s) {
  let out = null;
  let last = 0;
  for (let i = 0; i < s.length; i++) {
    const c = s.charCodeAt(i);
    let e = null;
    if (c === 38) e = '&amp;';
    else if (c === 60) e = '&lt;';
    else if (c === 62) e = '&gt;';
    else if (c === 34) e = '&quot;';
    else if (c === 39) e = '&#39;';
    if (e === null) continue;
    out = out === null ? s.slice(0, i) : out + s.slice(last, i);
    out += e;
    last = i + 1;
  }
  if (out === null) return s;
  return last < s.length ? out + s.slice(last) : out;
}

const MONTHS = ['January', 'February', 'March', 'April', 'May', 'June', 'July', 'August', 'September', 'October', 'November', 'December'];

/** A YYYY-MM-DD date in words, from the string alone. */
function longDate(date) {
  return `${Number(date.slice(8, 10))} ${MONTHS[Number(date.slice(5, 7)) - 1]} ${date.slice(0, 4)}`;
}

const MARKS_RE = /\p{M}/gu;

/** The slug of `text`, before memoisation: NFKD, marks dropped, lowered, runs of other characters one "-". */
function slugifyRaw(text) {
  const plain = text.normalize('NFKD').replace(MARKS_RE, '');
  let out = '';
  let gap = false;
  for (const ch of plain) {
    const cp = ch.codePointAt(0);
    let keep = null;
    if (cp >= 65 && cp <= 90) keep = String.fromCharCode(cp + 32);
    else if ((cp >= 97 && cp <= 122) || (cp >= 48 && cp <= 57)) keep = ch;
    if (keep === null) {
      gap = out.length > 0;
      continue;
    }
    if (gap) out += '-';
    gap = false;
    out += keep;
  }
  if (out.length > 64) out = out.slice(0, 64);
  let end = out.length;
  while (end > 0 && out.charCodeAt(end - 1) === 45) end--;
  if (end !== out.length) out = out.slice(0, end);
  return out === '' ? 'untitled' : out;
}

/** `slug` made unique against the `taken` set (and added to it): slug, slug-2, slug-3, ... */
function uniqueSlug(slug, taken) {
  let out = slug;
  for (let n = 2; taken.has(out); n++) out = `${slug}-${n}`;
  taken.add(out);
  return out;
}

/** Code-unit order (never the locale's). */
const byCodeUnits = (a, b) => (a < b ? -1 : a > b ? 1 : 0);

/** Whether every character of `line` is a space or a tab (the empty line counts). */
function isBlankST(line) {
  for (let i = 0; i < line.length; i++) {
    const c = line.charCodeAt(i);
    if (c !== 32 && c !== 9) return false;
  }
  return true;
}

/** `line` with spaces and tabs at both ends dropped. */
function trimST(line) {
  let a = 0;
  let b = line.length;
  while (a < b && (line.charCodeAt(a) === 32 || line.charCodeAt(a) === 9)) a++;
  while (b > a && (line.charCodeAt(b - 1) === 32 || line.charCodeAt(b - 1) === 9)) b--;
  return a === 0 && b === line.length ? line : line.slice(a, b);
}

/** Whether the code point is JavaScript whitespace (the \s class), for the few places it matters. */
function isWSCode(cp) {
  return cp === 32 || (cp >= 9 && cp <= 13) || cp === 0xa0 || cp === 0x1680 || (cp >= 0x2000 && cp <= 0x200a) || cp === 0x2028 || cp === 0x2029 || cp === 0x202f || cp === 0x205f || cp === 0x3000 || cp === 0xfeff;
}

